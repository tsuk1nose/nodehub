export function t(message: string, values: Record<string, string | number> = {}): string {
  const translated = locale.value === 'zh-CN' ? (zh[message] ?? message) : message
  return translated.replace(/\{(\w+)\}/g, (match, key: string) => String(values[key] ?? match))
}
export function setLocale(value: string) {
  locale.value = value === 'zh-CN' ? 'zh-CN' : 'en'
  try { localStorage.setItem('nodehub-language', locale.value) } catch { /* Keep the in-memory preference. */ }
  document.documentElement.lang = locale.value
}
document.documentElement.lang = locale.value
